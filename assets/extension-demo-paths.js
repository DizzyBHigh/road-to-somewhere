// Resolve extension-owned demo media to URLs that work with the site's base URL.
// Shared site assets (/assets/...) and fully-qualified URLs are left unchanged.
(function resolveExtensionDemoPaths() {
  const stylesheet = document.querySelector('link[href*="/assets/site.css"]');
  const siteRoot = stylesheet
    ? new URL(stylesheet.href, window.location.href).pathname.replace(/\/assets\/site\.css$/, '')
    : '';

  const pageBase = new URL(
    window.location.pathname.endsWith('/') ? window.location.href : `${window.location.href}/`
  );

  document.querySelectorAll('[data-demo-items]').forEach(card => {
    const raw = card.dataset.demoItems;
    if (!raw) return;

    try {
      const items = JSON.parse(raw);
      const resolved = items.map(item => {
        if (!item || typeof item.src !== 'string') return item;

        const src = item.src.trim();
        if (!src || /^(?:[a-z][a-z0-9+.-]*:|\/\/)/i.test(src)) return item;

        // Published extension paths are stored without a leading slash so
        // Jekyll can resolve them with relative_url. For demo media, make
        // them explicitly site-rooted so they are not resolved against the
        // extension page itself.
        if (src.startsWith('extensions/')) {
          return {
            ...item,
            src: `${siteRoot}/${src}`
          };
        }

        // Handle manifests generated by older importer versions that used
        // /extensions/... instead of a path relative to the site base URL.
        if (src.startsWith('/extensions/')) {
          return {
            ...item,
            src: `${siteRoot}${src}`
          };
        }

        // Extension-owned paths from manifests that have not been rewritten
        // are relative to the published extension page.
        if (src.startsWith('assets/')) {
          return {
            ...item,
            src: new URL(src, pageBase).href
          };
        }

        return item;
      });

      card.dataset.demoItems = JSON.stringify(resolved);
    } catch {
      // Leave malformed demo data untouched; the normal player will handle it.
    }
  });
})();
